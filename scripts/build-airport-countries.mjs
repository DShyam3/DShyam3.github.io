#!/usr/bin/env node
/**
 * build-airport-countries.mjs
 * ---------------------------
 * Turns OurAirports' airports.csv (public domain,
 * https://ourairports.com/data/) into src/features/travel/airport-countries.data.ts:
 * every IATA airport code, grouped under the ISO 3166-1 alpha-2 country it is in.
 *
 * A flight import carries airport codes only, so this is what lets the Travel
 * page say which countries a flight touched. It holds no personal data.
 *
 * Usage:
 *   curl -sSfL -o /some/empty/dir/airports.csv https://davidmegginson.github.io/ourairports-data/airports.csv
 *   node scripts/build-airport-countries.mjs /some/empty/dir/airports.csv
 *
 * Where a code is on more than one airport, the one with scheduled service
 * wins, then the larger type. OurAirports blanks `iata_code` on a closed
 * airport and keeps its old code in `keywords` (TXL, SXF), and lists some
 * alternate codes there too (MLH under BSL). Flights from before a closure
 * still carry those codes, so keyword codes are added below every listed one:
 * a code an open airport holds always keeps that owner.
 */

import { readFileSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = resolve(ROOT, 'src/features/travel/airport-countries.data.ts');
const input = process.argv[2];
if (!input) {
  console.error('Usage: node scripts/build-airport-countries.mjs <path to airports.csv>');
  process.exit(1);
}

/** RFC 4180 rows: quoted fields may hold commas, doubled quotes and newlines. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (quoted) {
      if (char === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (char === '"') quoted = false;
      else field += char;
    } else if (char === '"') quoted = true;
    else if (char === ',') { row.push(field); field = ''; }
    else if (char === '\n' || char === '\r') {
      if (char === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += char;
  }
  if (quoted) throw new Error('Unterminated quoted field');
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const TYPE_RANK = { large_airport: 5, medium_airport: 4, small_airport: 3, seaplane_base: 2, heliport: 1, balloonport: 0 };
const [header, ...records] = parseCsv(readFileSync(input, 'utf8'));
const column = name => {
  const index = header.indexOf(name);
  if (index < 0) throw new Error(`airports.csv has no "${name}" column`);
  return index;
};
const at = { type: column('type'), country: column('iso_country'), scheduled: column('scheduled_service'), iata: column('iata_code'), keywords: column('keywords') };
// Below every listed code (ranks 0-15): an open airport's keyword codes, then a closed one's.
const OPEN_KEYWORD_RANK = -1;
const CLOSED_RANK = -2;

const best = new Map();
let conflicts = 0;
function offer(iata, country, rank) {
  const previous = best.get(iata);
  if (previous) {
    if (previous.country !== country) conflicts++;
    if (previous.rank >= rank) return;
  }
  best.set(iata, { country, rank });
}
for (const record of records) {
  const country = record[at.country]?.trim().toUpperCase();
  const type = record[at.type];
  const open = type in TYPE_RANK;
  if (!/^[A-Z]{2}$/.test(country ?? '') || (!open && type !== 'closed')) continue;
  const iata = record[at.iata]?.trim().toUpperCase();
  if (/^[A-Z]{3}$/.test(iata ?? '')) offer(iata, country, open ? (record[at.scheduled] === 'yes' ? 10 : 0) + TYPE_RANK[type] : CLOSED_RANK);
  // Exactly three capitals only, so ordinary keywords ("Air", "RAF Station") stay out.
  for (const token of (record[at.keywords] ?? '').split(',').map(value => value.trim())) {
    if (/^[A-Z]{3}$/.test(token)) offer(token, country, open ? OPEN_KEYWORD_RANK : CLOSED_RANK);
  }
}

const byCountry = new Map();
for (const [iata, { country }] of best) byCountry.set(country, [...(byCountry.get(country) ?? []), iata]);
const body = [...byCountry.keys()].sort()
  .map(country => `  ${country}: '${byCountry.get(country).sort().join('')}',`)
  .join('\n');

writeFileSync(OUTPUT, `// Generated by scripts/build-airport-countries.mjs from OurAirports data (public domain).
// Do not edit by hand. Each value is that country's IATA airport codes, three letters each.
export const AIRPORT_CODES_BY_COUNTRY: Readonly<Record<string, string>> = {
${body}
};
`);
console.log(`${best.size} airport codes across ${byCountry.size} countries; ${conflicts} codes offered by more than one country, resolved by rank.`);
